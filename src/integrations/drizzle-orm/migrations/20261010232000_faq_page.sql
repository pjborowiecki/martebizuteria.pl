## Jewellery care

### How do I care for silver jewellery?

925 sterling silver naturally tarnishes over time on contact with air, moisture and cosmetics. After wearing your jewellery, wipe it with a soft, dry cloth and put it away in a dry place. You can clean tarnished silver without stones with a silver polishing cloth or with lukewarm water and a little mild soap, then rinse and dry it thoroughly. Do not use toothpaste, baking soda or scouring powder, which scratch silver, or products containing chlorine, which damage it. If the silver has deliberately darkened areas, clean them only with a dry cloth, because silver cleaners remove the darkening.

### How do I care for gold jewellery?

585 gold does not tarnish the way silver does, but cosmetics and everyday wear dull its shine over time. Wash it in lukewarm water with mild soap, remove dirt from crevices with a soft brush, then rinse the jewellery and dry it with a soft cloth. Take gold jewellery off before swimming in a pool and before cleaning, because chlorine and cleaning products can damage the alloy.

### How do I care for gold-plated jewellery?

Gold plating is a thin layer of gold on the surface of the jewellery, so it gradually wears away over time, fastest where the jewellery rubs against skin and clothes. Wipe it gently with a soft, dry cloth. Do not use polishing pastes or polishing cloths, because they remove the plating. Keep it away from perfume, creams and water.

### How do I care for jewellery with natural stones and pearls?

Natural stones and pearls can be sensitive to water, chemicals, high temperatures and knocks. Wipe them with a soft, slightly damp cloth and dry them straight away. Do not soak them, do not clean them with silver cleaners or in an ultrasonic cleaner, and keep them away from perfume and hairspray.

### When should I take my jewellery off?

Before bathing, swimming, using a sauna, exercising, cleaning and going to sleep. Put your jewellery on last, once your cosmetics, perfume and hairspray have dried.

